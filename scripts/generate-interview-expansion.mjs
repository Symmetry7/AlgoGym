import { writeFileSync } from "node:fs";

// One-time editorial import of public problem metadata. Titles, slugs, difficulty,
// and tags come from LeetCode's public catalog; no problem statements are copied.
const endpoint = "https://leetcode.com/graphql/";
const query = `query publicProblemCatalog($skip:Int,$limit:Int){questionList(categorySlug:"",skip:$skip,limit:$limit,filters:{}){data{title titleSlug difficulty isPaidOnly topicTags{name}}}}`;
const pages = [];
for (const skip of [0, 100, 200]) {
  const response = await fetch(endpoint, {
    method: "POST",
    headers: { "Content-Type": "application/json", Accept: "application/json" },
    body: JSON.stringify({ query, variables: { skip, limit: 100 } }),
    signal: AbortSignal.timeout(20000),
  });
  const body = await response.json();
  if (!response.ok || body.errors?.length || !Array.isArray(body.data?.questionList?.data))
    throw new Error(`LeetCode public catalog unavailable at ${skip}: ${response.status}`);
  pages.push(...body.data.questionList.data);
}

const problems = pages.filter((item) =>
  item && !item.isPaidOnly && /^[a-z0-9-]+$/.test(item.titleSlug) &&
  ["Easy", "Medium", "Hard"].includes(item.difficulty),
).slice(0, 200);
if (problems.length < 170) throw new Error(`Only ${problems.length} free problems found.`);
const sql = (value) => `'${String(value).replaceAll("'", "''")}'`;
const values = problems.map((item) => {
  const tags = (item.topicTags ?? []).slice(0, 3).map((tag) => sql(tag.name)).join(",");
  return `(${sql(`lc-${item.titleSlug}`)},${sql(item.title)},'LeetCode',${sql(`https://leetcode.com/problems/${item.titleSlug}/`)},${sql(item.difficulty)},array[${tags}]::text[])`;
});
const migration = `-- Independent AlgoGym practice expansion from LeetCode public catalog metadata.
-- These are editorial tracks, not verified employer interview-frequency data.
-- Premium-only problems, problem statements, and Hynts' compilation are excluded.
insert into public.interview_questions(id,title,source,url,difficulty,tags)
values\n${values.join(",\n")}
on conflict(id) do nothing;

-- Keep existing positions and user progress; append up to 40 new problems per
-- company from a rotated public catalog to provide deeper, varied practice.
with candidates as (
  select id, row_number() over(order by id)::integer - 1 as n
  from public.interview_questions
  where id in (${problems.map((item) => sql(`lc-${item.titleSlug}`)).join(",")})
), additions as (
  select c.slug, q.id, row_number() over(partition by c.slug order by ((q.n + c.position * 31) % ${problems.length}), q.id)::integer as rn
  from public.interview_companies c cross join candidates q
  where not exists (select 1 from public.interview_sheet_questions s where s.company_slug=c.slug and s.question_id=q.id)
)
insert into public.interview_sheet_questions(company_slug,question_id,position)
select slug,id,2000+rn from additions where rn<=40
on conflict do nothing;

-- The package sheet is a broad public-practice catalog. Bands are target study
-- routes, not claims about a company's compensation or a problem's interview use.
insert into public.interview_category_questions(category_slug,question_id,position)
select 'package-wise', id, row_number() over(order by id)::integer
from public.interview_questions where id in (${problems.map((item) => sql(`lc-${item.titleSlug}`)).join(",")})
on conflict do nothing;
`;
const target = process.argv[2];
if (!target) throw new Error("Pass the migration filename generated by Supabase CLI.");
writeFileSync(target, migration);
console.log(`Wrote ${problems.length} verified free public problems to ${target}`);
